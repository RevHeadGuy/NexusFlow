"""PRD generator agent.

Produces a product requirements document from the idea and brief. Output matches
the ``prd_generator`` guardrail schema entry.
"""
from __future__ import annotations

from pydantic import BaseModel, Field

from app.agents.base import BaseAgent


class PrdOutput(BaseModel):
    model_config = {"extra": "allow"}

    title: str = Field(..., min_length=3)
    overview: str | dict = Field(...)
    features: list = Field(..., min_length=1)
    user_stories: list = Field(..., min_length=1)
    acceptance_criteria: list = Field(..., min_length=1)


PRD_PROMPT = """
You are the Product Manager for NexusFlow. Write a focused product requirements document.

Requirements:
- Give the product a clear title and a concise overview of the problem and solution.
- Define a prioritized feature list (must-have / should-have / nice-to-have).
- Write user stories in the "As a <role>, I want <goal> so that <benefit>" form.
- Define measurable, testable acceptance criteria.
- Keep scope grounded in the provided brief; mark unvalidated items as assumptions.
- Output valid structured JSON matching the requested schema.
"""


class PrdAgent(BaseAgent):
    agent_name = "prd_generator"
    output_schema = PrdOutput
    default_prompt = PRD_PROMPT
    max_output_tokens = 6000
    mock_sample = {
        "title": "Product Requirements Document",
        "overview": "A concise statement of the problem this product solves and the proposed approach, derived from the project brief.",
        "features": [
            {"name": "Core workflow", "description": "The primary end-to-end user journey.", "priority": "must-have"},
            {"name": "Review and approval", "description": "Human checkpoints before continuing.", "priority": "must-have"},
        ],
        "user_stories": [
            "As a user, I want to submit my idea so that the system can structure it.",
            "As a reviewer, I want to approve or request changes so that quality is controlled.",
        ],
        "acceptance_criteria": [
            "A user can complete the core workflow without data loss.",
            "Approvals are persisted and auditable.",
        ],
    }


def _as_text(value) -> str:
    if value is None:
        return ""
    if isinstance(value, str):
        return value
    if isinstance(value, list):
        return ", ".join(_as_text(item) for item in value)
    if isinstance(value, dict):
        return "; ".join(f"{k}: {_as_text(v)}" for k, v in value.items())
    return str(value)


def _render_feature(f) -> str:
    if not isinstance(f, dict):
        return f"- {_as_text(f)}"
    name = f.get("name") or f.get("feature") or "Feature"
    priority = f.get("priority", "should-have")
    description = _as_text(f.get("description", ""))
    return f"- **{_as_text(name)}** ({priority}): {description}"


def render_prd(project_name: str, data: dict) -> str:
    """Render the structured PRD output as a Markdown artifact."""
    features = "\n".join(_render_feature(f) for f in data.get("features", []))
    stories = "\n".join(f"- {_as_text(item)}" for item in data.get("user_stories", []))
    criteria = "\n".join(f"- {_as_text(item)}" for item in data.get("acceptance_criteria", []))
    return f"""# {data.get('title', 'Product Requirements')}: {project_name}

> Generated by the PRD agent from the project brief. Confirm scope with the project owner before implementation.

## Overview

{_as_text(data.get('overview', 'Not provided.'))}

## Features

{features or '- None defined.'}

## User stories

{stories or '- None defined.'}

## Acceptance criteria

{criteria or '- None defined.'}
"""
