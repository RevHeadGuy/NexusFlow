"""Technical feasibility agent.

Assesses the technical feasibility of the idea and recommends a stack. Output
matches the ``technical_feasibility`` guardrail schema entry.
"""
from __future__ import annotations

from pydantic import BaseModel, Field

from app.agents.base import BaseAgent


class TechnicalFeasibilityOutput(BaseModel):
    model_config = {"extra": "allow"}

    recommended_stack: list = Field(..., min_length=1)
    build_vs_buy: str | dict = Field(...)
    complexity_score: int | float | str = Field(...)
    technical_risks: list = Field(..., min_length=1)


TECHNICAL_FEASIBILITY_PROMPT = """
You are the Technical Feasibility Engineer for NexusFlow. Assess whether a product idea is buildable.

Requirements:
- Recommend a concrete, mainstream technology stack appropriate to the idea.
- Give a build-vs-buy judgement for the hardest components.
- Rate overall complexity on a 1-10 scale (1 trivial, 10 research-grade).
- List real technical risks with a severity and a mitigation.
- Do not overstate certainty; flag assumptions that need validation with engineering owners.
- Output valid structured JSON matching the requested schema.
"""


class TechnicalFeasibilityAgent(BaseAgent):
    agent_name = "technical_feasibility"
    output_schema = TechnicalFeasibilityOutput
    default_prompt = TECHNICAL_FEASIBILITY_PROMPT
    max_output_tokens = 3000
    mock_sample = {
        "recommended_stack": ["Web client", "API service", "Relational database", "Background worker"],
        "build_vs_buy": "Build the core domain logic; buy auth and infrastructure where mature managed options exist.",
        "complexity_score": 5,
        "technical_risks": [
            {
                "risk": "Scope and data requirements are not yet validated.",
                "severity": "medium",
                "mitigation": "Confirm expected scale, data categories, and integrations with engineering before committing.",
            }
        ],
    }


def _as_text(value) -> str:
    if value is None:
        return ""
    if isinstance(value, str):
        return value
    if isinstance(value, list):
        return ", ".join(_as_text(item) for item in value)
    if isinstance(value, dict):
        return "; ".join(f"{k}: {_as_text(v)}" for k, v in value.items())
    return str(value)


def _render_risk(r) -> str:
    if not isinstance(r, dict):
        return f"### {_as_text(r)}"
    title = r.get("risk") or r.get("name") or "Risk"
    severity = r.get("severity", "medium")
    mitigation = _as_text(r.get("mitigation")) or "None recorded"
    return f"### {_as_text(title)} ({severity})\n\n- Mitigation: {mitigation}"


def render_technical_feasibility(project_name: str, data: dict) -> str:
    """Render the structured feasibility output as a Markdown artifact."""
    stack = "\n".join(f"- {_as_text(item)}" for item in data.get("recommended_stack", []))
    risks = "\n\n".join(_render_risk(r) for r in data.get("technical_risks", [])) or "No risks identified."
    return f"""# Technical Feasibility: {project_name}

> Generated by the Technical Feasibility agent. Validate these choices against real requirements and security review before implementation.

## Recommended stack

{stack or '- Not specified.'}

## Build vs. buy

{_as_text(data.get('build_vs_buy', 'Not assessed.'))}

## Overall complexity

{data.get('complexity_score', 'n/a')} / 10

## Technical risks

{risks}
"""
