"""Architecture agent.

Produces a system architecture outline from the idea, brief, and (when available)
the PRD. Output matches the ``architecture_agent`` guardrail schema entry.
"""
from __future__ import annotations

from pydantic import BaseModel, Field

from app.agents.base import BaseAgent


class ArchitectureOutput(BaseModel):
    model_config = {"extra": "allow"}

    components: list = Field(..., min_length=1)
    data_flow: str | dict | list = Field(...)
    tech_stack: list = Field(..., min_length=1)
    infrastructure: str | dict = Field(...)


ARCHITECTURE_PROMPT = """
You are the Software Architect for NexusFlow. Draft a system architecture outline.

Requirements:
- Define the major components and each one's responsibility.
- Describe the data flow between components in prose.
- Recommend a concrete, mainstream tech stack consistent with the feasibility assessment.
- Describe the infrastructure and deployment shape at a high level.
- Call out quality attributes (auth, auditability, reliability) that must be designed in.
- Do not present this as a validated architecture; mark decisions that need confirmation.
- Output valid structured JSON matching the requested schema.
"""


class ArchitectureAgent(BaseAgent):
    agent_name = "architecture_agent"
    output_schema = ArchitectureOutput
    default_prompt = ARCHITECTURE_PROMPT
    max_output_tokens = 4000
    mock_sample = {
        "components": [
            {"name": "Web client", "responsibility": "User workflows and review surfaces."},
            {"name": "API service", "responsibility": "Validation, authorization, and domain operations."},
            {"name": "Persistent store", "responsibility": "Projects, decisions, and versioned artifacts."},
        ],
        "data_flow": "The client calls the API over HTTP/JSON; the API validates, authorizes, and persists to the store, returning structured responses.",
        "tech_stack": ["React/Next.js frontend", "FastAPI backend", "Relational database"],
        "infrastructure": "Single-region managed hosting for the API and database, with secrets held in the backend environment. Confirm scale and recovery targets before finalizing.",
    }


def _as_text(value) -> str:
    if value is None:
        return ""
    if isinstance(value, str):
        return value
    if isinstance(value, list):
        return ", ".join(_as_text(item) for item in value)
    if isinstance(value, dict):
        return "; ".join(f"{k}: {_as_text(v)}" for k, v in value.items())
    return str(value)


def _render_component(c) -> str:
    if not isinstance(c, dict):
        return f"- {_as_text(c)}"
    name = c.get("name") or c.get("component") or "Component"
    responsibility = _as_text(c.get("responsibility") or c.get("description", ""))
    return f"- **{_as_text(name)}**: {responsibility}"


def render_architecture(project_name: str, data: dict) -> str:
    """Render the structured architecture output as a Markdown artifact."""
    components = "\n".join(_render_component(c) for c in data.get("components", []))
    stack = "\n".join(f"- {_as_text(item)}" for item in data.get("tech_stack", []))
    return f"""# Architecture Outline: {project_name}

> Generated by the Architecture agent. This is a starting outline, not a validated architecture. Confirm requirements before selecting production technologies.

## Components

{components or '- None defined.'}

## Data flow

{_as_text(data.get('data_flow', 'Not described.'))}

## Tech stack

{stack or '- Not specified.'}

## Infrastructure

{_as_text(data.get('infrastructure', 'Not described.'))}
"""
