"""Quality evaluator agent.

Reviews the assembled project artifacts and produces findings. Output matches the
``quality_evaluator`` guardrail schema entry. This complements the deterministic
rule-based evaluations already produced by ``evaluation_service``.
"""
from __future__ import annotations

from pydantic import BaseModel, Field

from app.agents.base import BaseAgent


class QualityEvaluationOutput(BaseModel):
    model_config = {"extra": "allow"}

    findings: list = Field(..., min_length=1)
    summary: str | dict = Field(...)
    overall_score: float | int | str = Field(...)


QUALITY_EVALUATOR_PROMPT = """
You are the Quality Evaluator for NexusFlow, acting as a critical reviewer.

Requirements:
- Review the provided project context and artifacts for gaps, inconsistencies, and unsupported claims.
- Produce specific findings, each with a severity (low/medium/high/critical), a description, and a recommendation.
- Challenge weak assumptions directly (Devil's Advocate), but stay fair and evidence-based.
- Give an overall quality score between 0 and 1.
- Write a short summary of the project's readiness.
- Output valid structured JSON matching the requested schema.
"""


class QualityEvaluatorAgent(BaseAgent):
    agent_name = "quality_evaluator"
    output_schema = QualityEvaluationOutput
    default_prompt = QUALITY_EVALUATOR_PROMPT
    max_output_tokens = 3000
    mock_sample = {
        "findings": [
            {
                "title": "Market claims are not yet source-backed",
                "severity": "medium",
                "description": "Opportunity and sizing statements rely on assumptions rather than validated evidence.",
                "recommendation": "Add primary research sources before treating the market as validated.",
            }
        ],
        "summary": "The planning artifacts are internally coherent but depend on several assumptions that need validation before build.",
        "overall_score": 0.6,
    }


def _as_text(value) -> str:
    if value is None:
        return ""
    if isinstance(value, str):
        return value
    if isinstance(value, list):
        return ", ".join(_as_text(item) for item in value)
    if isinstance(value, dict):
        return "; ".join(f"{k}: {_as_text(v)}" for k, v in value.items())
    return str(value)


def _render_finding(f) -> str:
    if not isinstance(f, dict):
        return f"### {_as_text(f)}"
    severity = str(f.get("severity", "medium")).upper()
    title = f.get("title") or f.get("name") or "Finding"
    description = _as_text(f.get("description", ""))
    recommendation = _as_text(f.get("recommendation")) or "None recorded"
    return f"### [{severity}] {_as_text(title)}\n\n{description}\n\n**Recommendation:** {recommendation}"


def _score_text(score) -> str:
    try:
        value = float(score)
        # Accept either 0-1 or 0-100 scales.
        if value > 1:
            value = value / 100
        return f"{round(value * 100)}%"
    except (TypeError, ValueError):
        return "n/a"


def render_quality_review(project_name: str, data: dict) -> str:
    """Render the structured quality-evaluation output as a Markdown artifact."""
    findings = "\n\n".join(_render_finding(f) for f in data.get("findings", [])) or "No findings recorded."
    score_text = _score_text(data.get("overall_score"))
    return f"""# Quality Review: {project_name}

> Generated by the Quality Evaluator agent, alongside the deterministic consistency and Devil's Advocate checks.

## Overall readiness

{score_text}

## Summary

{_as_text(data.get('summary', 'Not provided.'))}

## Findings

{findings}
"""
