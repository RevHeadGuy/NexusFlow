"""Market research agent.

Produces a structured market-research analysis from the project idea and brief.
The output schema matches the ``market_research`` entry in the guardrail schema
registry so the standard guardrail chain validates it.
"""
from __future__ import annotations

from pydantic import BaseModel, Field

from app.agents.base import BaseAgent


class MarketResearchOutput(BaseModel):
    """Forgiving schema for a rich, human-reviewed artifact.

    Sub-structures accept whatever shape the model returns (object or list of
    objects/strings); the Markdown renderer normalizes them. Only the required
    top-level keys and their non-emptiness are enforced, matching the guardrail
    schema registry.
    """

    model_config = {"extra": "allow"}

    competitors: list = Field(..., min_length=1)
    market_size: str | dict = Field(...)
    user_personas: list = Field(..., min_length=1)
    opportunities: list = Field(..., min_length=1)
    risks: list = Field(..., min_length=1)


MARKET_RESEARCH_PROMPT = """
You are the Market Research Analyst for NexusFlow. Analyze the market around a product idea.

Requirements:
- Identify plausible competitors with positioning, strengths, and weaknesses.
- Describe the market size qualitatively; do not fabricate precise figures or cite sources you were not given.
- Define concrete user personas with their needs.
- List genuine opportunities and risks grounded in the idea.
- Clearly mark anything that is an assumption rather than a known fact.
- Output valid structured JSON matching the requested schema.
"""


class MarketResearchAgent(BaseAgent):
    agent_name = "market_research"
    output_schema = MarketResearchOutput
    default_prompt = MARKET_RESEARCH_PROMPT
    max_output_tokens = 3000
    mock_sample = {
        "competitors": [
            {
                "name": "Established incumbent",
                "positioning": "Broad enterprise suite covering adjacent needs.",
                "strengths": ["brand trust", "existing integrations"],
                "weaknesses": ["slow to adapt", "high cost"],
            }
        ],
        "market_size": "The addressable market is plausibly meaningful but not independently sized here; validate with primary research before planning.",
        "user_personas": [
            {
                "name": "Primary buyer",
                "description": "The role that feels the problem most acutely.",
                "needs": ["clear value", "low switching cost"],
            }
        ],
        "opportunities": ["underserved segment", "integration gap in incumbents"],
        "risks": ["incumbent response", "unvalidated willingness to pay"],
    }


def _as_text(value) -> str:
    """Render a value that may be a string, list, or dict as readable text."""
    if value is None:
        return ""
    if isinstance(value, str):
        return value
    if isinstance(value, list):
        return ", ".join(_as_text(item) for item in value)
    if isinstance(value, dict):
        return "; ".join(f"{k}: {_as_text(v)}" for k, v in value.items())
    return str(value)


def _entry(item, *name_keys: str) -> tuple[str, dict]:
    """Return (title, mapping) for an item that may be a dict or a plain string."""
    if isinstance(item, dict):
        for key in name_keys:
            if item.get(key):
                return str(item[key]), item
        return _as_text(item), item
    return str(item), {}


def _render_markdown(project_name: str, data: dict) -> str:
    competitors = "\n\n".join(
        (lambda title, c: (
            f"### {title}\n\n"
            f"- Positioning: {_as_text(c.get('positioning', ''))}\n"
            f"- Strengths: {_as_text(c.get('strengths')) or 'None recorded'}\n"
            f"- Weaknesses: {_as_text(c.get('weaknesses')) or 'None recorded'}"
        ))(*_entry(c, "name", "competitor"))
        for c in data.get("competitors", [])
    ) or "No competitors identified."
    personas = "\n\n".join(
        (lambda title, p: (
            f"### {title}\n\n{_as_text(p.get('description', ''))}\n\n"
            f"- Needs: {_as_text(p.get('needs')) or 'None recorded'}"
        ))(*_entry(p, "name", "persona"))
        for p in data.get("user_personas", [])
    ) or "No personas identified."
    opportunities = "\n".join(f"- {_as_text(item)}" for item in data.get("opportunities", []))
    risks = "\n".join(f"- {_as_text(item)}" for item in data.get("risks", []))
    market_size = _as_text(data.get("market_size", "Not assessed."))
    return f"""# Market Research: {project_name}

> Generated by the Market Research agent from the project idea and brief. Treat qualitative claims as assumptions until validated with primary sources.

## Market size

{market_size}

## Competitors

{competitors}

## User personas

{personas}

## Opportunities

{opportunities or '- None identified.'}

## Risks

{risks or '- None identified.'}
"""


def render_market_research(project_name: str, data: dict) -> str:
    """Render the structured market-research output as a Markdown artifact."""
    return _render_markdown(project_name, data)
